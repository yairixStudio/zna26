(function applyOfficialZnaLineup() {
  const existingById = new Map((ARTISTS || []).map(artist => [artist.id, artist]));
  const BROKEN_LINKS = new Set([
    "http://www.jotisidhu.com/",
    "http://www.dogma3000.com/",
    "https://www.gms-music.com/",
    "https://djsolitare.com/",
    "https://www.boshkebeats.com",
    "https://open.spotify.com/artist/1QqxPdbBp2hsHuKCDDCOL5"
  ]);

  function normalizeUrl(url) {
    if (!url) return "";
    return /^www\./i.test(url) ? `https://${url}` : url;
  }

  function mergeUniqueLinks(primary = [], fallback = []) {
    const seen = new Set();
    return [...primary, ...fallback].map(link => (
      link && link.url ? { ...link, url: normalizeUrl(link.url) } : link
    )).filter(link => {
      if (!link || !link.url || BROKEN_LINKS.has(link.url) || seen.has(link.url)) return false;
      seen.add(link.url);
      return true;
    });
  }

  function normalizeChannels(channels = {}) {
    return Object.fromEntries(
      Object.entries(channels)
        .map(([platform, url]) => [platform, normalizeUrl(url)])
        .filter(([, url]) => url && !BROKEN_LINKS.has(url))
    );
  }

  ARTISTS = OFFICIAL_ZNA_2026_ARTISTS.map(official => {
    const curated = existingById.get(official.curatedFrom || official.id) || existingById.get(official.id) || {};
    return {
      ...curated,
      ...official,
      realName: official.realName || curated.realName || '',
      age: curated.age || official.age || null,
      born: curated.born || official.born || '',
      tags: official.tags || curated.tags || [],
      links: mergeUniqueLinks(official.links, curated.links),
      channels: { ...normalizeChannels(curated.channels), ...normalizeChannels(official.channels) },
      albums: official.albums?.length ? official.albums : (curated.albums || []),
      tracks: official.tracks?.length ? official.tracks : (curated.tracks || [])
    };
  });
})();
